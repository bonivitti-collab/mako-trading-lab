import { NextRequest, NextResponse } from "next/server";

export async function POST(req: NextRequest) {
  try {
    const { prompt, product_type } = await req.json();

    if (!prompt) {
      return NextResponse.json({ error: "Prompt is required" }, { status: 400 });
    }

    const apiKey = process.env.GEMINI_API_KEY;
    const isEa = (product_type === "ea" || !product_type);

    const systemInstruction = `
You are an expert MQL5 algorithmic engineer for MetaTrader 5.
Generate clean, production-grade, bug-free MQL5 code based on the user's prompt.
Strict rules:
1. Include #property strict and #property version "1.00".
2. If it is an EA, include <Trade\\Trade.mqh> and use CTrade for order executions.
3. Include inputs for Risk %, Stop Loss, and Take Profit.
4. Ensure array bounds checking and safe historical data checks.
5. Provide complete, fully compilable code with zero syntax errors or placeholders.
`;

    // If an API key is configured, call Google Gemini 2.5 Flash
    if (apiKey) {
      const response = await fetch(`https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${apiKey}`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          systemInstruction: { parts: [{ text: systemInstruction }] },
          contents: [{ parts: [{ text: `Generate a complete MQL5 ${isEa ? "Expert Advisor" : "Indicator"}: ${prompt}` }] }],
          generationConfig: { temperature: 0.2, maxOutputTokens: 3000 }
        })
      });

      const data = await response.json();
      const rawText = data?.candidates?.[0]?.content?.parts?.[0]?.text || "";
      // Strip markdown code fences if present
      const cleanCode = rawText.replace(/^```mql5\n|^```cpp\n|^```\n|```$/gm, "");
      
      return NextResponse.json({
        code: cleanCode,
        model: "gemini-2.5-flash",
        success: true
      });
    }

    // High quality template fallback if Gemini API key is not yet set in environment
    const generatedSample = `//+------------------------------------------------------------------+
//|                                                 CustomGenerated.mq5 |
//|                                     Generated by Mako AI Studio |
//|                                      https://makotradinglab.com  |
//+------------------------------------------------------------------+
#property copyright "Generated by Mako AI Studio"
#property link      "https://makotradinglab.com"
#property version   "1.00"
#property strict

#include <Trade\\Trade.mqh>

input group "--- Strategy Parameters ---"
input int    InpPeriodEMA       = 20;    // Trend EMA Period
input double InpRiskPercent     = 1.0;   // Risk per trade (%)
input double InpStopLossPips    = 25.0;  // Stop Loss in Pips
input double InpTakeProfitPips  = 50.0;  // Take Profit in Pips
input ulong  InpMagicNumber     = 778899;// Magic Number

CTrade MakoTrade;
int    handleEMA;

int OnInit()
{
   MakoTrade.SetExpertMagicNumber(InpMagicNumber);
   handleEMA = iMA(_Symbol, _Period, InpPeriodEMA, 0, MODE_EMA, PRICE_CLOSE);
   if(handleEMA == INVALID_HANDLE)
   {
      Print("Failed to create EMA handle.");
      return(INIT_FAILED);
   }
   Print("Mako AI Bot initialized successfully.");
   return(INIT_SUCCEEDED);
}

void OnDeinit(const int reason)
{
   IndicatorRelease(handleEMA);
}

void OnTick()
{
   // Check bar close (run once per candle)
   static datetime lastBar = 0;
   datetime currentBar = iTime(_Symbol, _Period, 0);
   if(currentBar == lastBar) return;
   lastBar = currentBar;
   
   // Query EMA buffer
   double ema[];
   ArraySetAsSeries(ema, true);
   if(CopyBuffer(handleEMA, 0, 1, 2, ema) < 2) return;
   
   MqlRates rates[];
   ArraySetAsSeries(rates, true);
   if(CopyRates(_Symbol, _Period, 1, 2, rates) < 2) return;
   
   // Logic according to prompt: ${prompt}
   bool buyCondition  = (rates[0].close > ema[0] && rates[1].close <= ema[1]);
   bool sellCondition = (rates[0].close < ema[0] && rates[1].close >= ema[1]);
   
   if(PositionsTotal() == 0)
   {
      double ask = SymbolInfoDouble(_Symbol, SYMBOL_ASK);
      double bid = SymbolInfoDouble(_Symbol, SYMBOL_BID);
      double point = SymbolInfoDouble(_Symbol, SYMBOL_POINT);
      
      if(buyCondition)
      {
         double sl = ask - (InpStopLossPips * 10 * point);
         double tp = ask + (InpTakeProfitPips * 10 * point);
         MakoTrade.Buy(0.1, _Symbol, ask, sl, tp, "Mako AI Pullback");
      }
      else if(sellCondition)
      {
         double sl = bid + (InpStopLossPips * 10 * point);
         double tp = bid - (InpTakeProfitPips * 10 * point);
         MakoTrade.Sell(0.1, _Symbol, bid, sl, tp, "Mako AI Pullback");
      }
   }
}
`;

    return NextResponse.json({
      code: generatedSample,
      model: "mako-engine-fallback",
      note: "Add GEMINI_API_KEY to your .env to connect live Gemini Cloud AI",
      success: true
    });

  } catch (err: any) {
    return NextResponse.json({ error: err.message }, { status: 500 });
  }
}
